// templsite requires the older stand-in; the newer one is what a tool
// looked up on its own would get.
const (
	requiredTempl = "v0.1.0"
	newerTempl    = "v0.2.0"
)

// goIn runs a go command in dir and returns its trimmed output.
func goIn(t *testing.T, dir string, args ...string) string {
	t.Helper()
	cmd := exec.Command("go", args...)
	cmd.Dir = dir
	out, err := cmd.CombinedOutput()
	if err != nil {
		t.Fatalf("go %s in %s: %v\n%s", strings.Join(args, " "), dir, err, out)
	}
	return strings.TrimSpace(string(out))
}

// A new site carries templ as a tool with no version of its own, and it
// resolves to the templ templsite requires even when a newer templ is
// available. Its components are generated by that templ, never by the
// one on PATH.
func TestSetUpModuleTakesTemplFromTemplsite(t *testing.T) {
	modproxy.Serve(t, modproxy.Templ(requiredTempl), modproxy.Templ(newerTempl))
	templsite := modproxy.Templsite(t, requiredTempl)

	decoys := t.TempDir()
	marker := filepath.Join(decoys, "called")
	if err := os.WriteFile(filepath.Join(decoys, "templ"), []byte("#!/bin/sh\ntouch "+marker+"\nexit 1\n"), 0o755); err != nil {
		t.Fatal(err)
	}
	t.Setenv("PATH", decoys+string(os.PathListSeparator)+os.Getenv("PATH"))

	// The shape the scaffold has: main imports templsite and the site's
	// components, which are .templ files beside a plain Go file.
	site := filepath.Join(t.TempDir(), "mysite")
	modproxy.WriteFiles(t, site, map[string]string{
		"main.go":                "package main\n\nimport (\n\t_ \"github.com/dmoose/templsite/pkg/site\"\n\n\t_ \"mysite/components\"\n)\n\nfunc main() {}\n",
		"components/data.go":     "package components\n",
		"components/hello.templ": "package components\n\ntempl Hello() {\n\t<p>hello</p>\n}\n",
	})
	if err := setUpModule(context.Background(), site, "mysite", templsite); err != nil {
		t.Fatalf("setUpModule: %v", err)
	}

	var mod struct {
		Tool []struct{ Path string }
	}
	if err := json.Unmarshal([]byte(goIn(t, site, "mod", "edit", "-json")), &mod); err != nil {
		t.Fatal(err)
	}
	if len(mod.Tool) != 1 || mod.Tool[0].Path != modproxy.TemplTool {
		t.Errorf("tools = %+v, want templ alone", mod.Tool)
	}
	if got := goIn(t, site, "list", "-m", "-f", "{{.Version}}", modproxy.TemplPath); got != requiredTempl {
		t.Errorf("site resolves templ %s, templsite requires %s", got, requiredTempl)
	}
	gen, err := os.ReadFile(filepath.Join(site, "components", "hello_templ.go"))
	if err != nil {
		t.Fatalf("components were not generated: %v", err)
	}
	if !strings.Contains(string(gen), "// templ: version: "+requiredTempl+"\n") {
		t.Errorf("hello_templ.go is not stamped %s:\n%s", requiredTempl, gen)
	}
	if _, err := os.Stat(marker); err == nil {
		t.Error("templ on PATH was called")
	}
}
