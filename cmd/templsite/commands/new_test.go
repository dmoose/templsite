// fixtureTempl is older than the newest templ in the module cache, so a
// site that took the newest release instead of templsite's requirement
// shows up as the wrong version.
const fixtureTempl = "v0.3.1100"

// goIn runs a go command in dir and returns its trimmed output.
func goIn(t *testing.T, dir string, args ...string) string {
	t.Helper()
	cmd := exec.Command("go", args...)
	cmd.Dir = dir
	out, err := cmd.CombinedOutput()
	if err != nil {
		t.Fatalf("go %s in %s: %v\n%s", strings.Join(args, " "), dir, err, out)
	}
	return strings.TrimSpace(string(out))
}

// cacheProxy serves module queries, "latest" included, from the module
// cache, so tidy behaves as it does online without the network.
func cacheProxy(t *testing.T) {
	t.Helper()
	t.Setenv("GOWORK", "off")
	t.Setenv("GOFLAGS", "-mod=mod")
	modcache := goIn(t, ".", "env", "GOMODCACHE")
	t.Setenv("GOPROXY", "file://"+filepath.Join(modcache, "cache", "download"))
	t.Setenv("GOSUMDB", "off")
}

// fixtureTemplsite copies this module's packages to a temp dir as a
// templsite whose go.mod requires fixtureTempl.
func fixtureTemplsite(t *testing.T) string {
	t.Helper()
	repo, err := filepath.Abs(filepath.Join("..", "..", ".."))
	if err != nil {
		t.Fatal(err)
	}
	dir := t.TempDir()
	for _, name := range []string{"pkg", "internal"} {
		if err := os.CopyFS(filepath.Join(dir, name), os.DirFS(filepath.Join(repo, name))); err != nil {
			t.Fatal(err)
		}
	}
	// As templsite was before templ became its tool: templ lowered and the
	// tool line gone, so tidy drops what only the templ command needed.
	if err := os.WriteFile(filepath.Join(dir, "go.mod"), []byte(goIn(t, repo, "mod", "edit", "-print")+"\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	goIn(t, dir, "mod", "edit", "-require=github.com/a-h/templ@"+fixtureTempl, "-droptool=github.com/a-h/templ/cmd/templ")
	// templsite's own generated components import templ; this stands in.
	if err := os.MkdirAll(filepath.Join(dir, "components"), 0o755); err != nil {
		t.Fatal(err)
	}
	uses := "package components\n\nimport \"github.com/a-h/templ\"\n\nvar _ templ.Component\n"
	if err := os.WriteFile(filepath.Join(dir, "components", "uses.go"), []byte(uses), 0o644); err != nil {
		t.Fatal(err)
	}
	goIn(t, dir, "mod", "tidy")
	if got := goIn(t, dir, "list", "-m", "-f", "{{.Version}}", "github.com/a-h/templ"); got != fixtureTempl {
		t.Fatalf("fixture templsite resolves templ %s, want %s", got, fixtureTempl)
	}
	versions := strings.Fields(goIn(t, dir, "list", "-m", "-versions", "github.com/a-h/templ"))
	if i := slices.Index(versions, fixtureTempl); i < 0 || i == len(versions)-1 {
		t.Skipf("no templ newer than %s in the module cache: %v", fixtureTempl, versions)
	}
	return dir
}

// A new site carries templ as a tool with no version of its own, and it
// resolves to the templ templsite requires, even when a newer templ is
// available. Its components are generated by that templ, never by the one
// on PATH.
func TestNewTakesTemplFromTemplsite(t *testing.T) {
	cacheProxy(t)
	templsite := fixtureTemplsite(t)

	decoys := t.TempDir()
	marker := filepath.Join(decoys, "called")
	if err := os.WriteFile(filepath.Join(decoys, "templ"), []byte("#!/bin/sh\ntouch "+marker+"\nexit 1\n"), 0o755); err != nil {
		t.Fatal(err)
	}
	t.Setenv("PATH", decoys+string(os.PathListSeparator)+os.Getenv("PATH"))

	work := t.TempDir()
	t.Chdir(work)
	if err := runNew(context.Background(), "mysite", "fastatic", false, templsite); err != nil {
		t.Fatalf("runNew: %v", err)
	}
	site := filepath.Join(work, "mysite")

	var mod struct {
		Tool []struct{ Path string }
	}
	if err := json.Unmarshal([]byte(goIn(t, site, "mod", "edit", "-json")), &mod); err != nil {
		t.Fatal(err)
	}
	if len(mod.Tool) != 1 || mod.Tool[0].Path != "github.com/a-h/templ/cmd/templ" {
		t.Errorf("tools = %+v, want templ alone", mod.Tool)
	}
	if got := goIn(t, site, "list", "-m", "-f", "{{.Version}}", "github.com/a-h/templ"); got != fixtureTempl {
		t.Errorf("site resolves templ %s, templsite requires %s", got, fixtureTempl)
	}

	gen, err := os.ReadFile(filepath.Join(site, "components", "layout", "base_templ.go"))
	if err != nil {
		t.Fatalf("components were not generated: %v", err)
	}
	if !strings.Contains(string(gen), "// templ: version: "+fixtureTempl+"\n") {
		t.Errorf("base_templ.go is not stamped %s", fixtureTempl)
	}
	if _, err := os.Stat(marker); err == nil {
		t.Error("templ on PATH was called")
	}
}
