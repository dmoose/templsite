// Package modproxy serves small fake modules to the go command for tests,
// from a GOPROXY directory and an empty module cache in the test's temp
// dir, so a test never reads the machine's module cache or the network.
package modproxy

import (
	"archive/zip"
	"encoding/json"
	"os"
	"path/filepath"
	"slices"
	"strings"
	"testing"
)

// TemplPath is the module path the templ stand-in takes.
const TemplPath = "github.com/a-h/templ"

// TemplTool is the stand-in generator as a go.mod tool.
const TemplTool = TemplPath + "/cmd/templ"

// Module is one version of a fake module: its files, go.mod included.
type Module struct {
	Path    string
	Version string
	Files   map[string]string
}

// Serve writes a proxy for mods and points the go command at it, with a
// fresh module cache, no checksum database and no toolchain switching.
func Serve(t *testing.T, mods ...Module) {
	t.Helper()
	proxy := t.TempDir()
	versions := map[string][]string{}
	for _, m := range mods {
		dir := filepath.Join(proxy, m.Path, "@v")
		if err := os.MkdirAll(dir, 0o755); err != nil {
			t.Fatal(err)
		}
		info, err := json.Marshal(map[string]string{"Version": m.Version, "Time": "2026-01-01T00:00:00Z"})
		if err != nil {
			t.Fatal(err)
		}
		write(t, filepath.Join(dir, m.Version+".info"), string(info))
		write(t, filepath.Join(dir, m.Version+".mod"), m.Files["go.mod"])
		writeZip(t, filepath.Join(dir, m.Version+".zip"), m)
		versions[m.Path] = append(versions[m.Path], m.Version)
	}
	for path, vs := range versions {
		slices.Sort(vs)
		write(t, filepath.Join(proxy, path, "@v", "list"), strings.Join(vs, "\n")+"\n")
	}
	t.Setenv("GOPROXY", "file://"+filepath.ToSlash(proxy))
	t.Setenv("GOMODCACHE", t.TempDir())
	t.Setenv("GOFLAGS", "-mod=mod -modcacherw")
	t.Setenv("GOSUMDB", "off")
	t.Setenv("GONOSUMDB", "")
	t.Setenv("GOPRIVATE", "")
	t.Setenv("GONOPROXY", "")
	t.Setenv("GOWORK", "off")
	t.Setenv("GOTOOLCHAIN", "local")
}

// Templ is a stand-in for templ at version: a Component type and a
// cmd/templ whose `generate [-path dir]` writes, for every .templ file, a
// _templ.go stamped with this version that imports the runtime.
func Templ(version string) Module {
	return Module{Path: TemplPath, Version: version, Files: map[string]string{
		"go.mod":            "module " + TemplPath + "\n\ngo 1.26\n",
		"templ.go":          "package templ\n\nimport (\n\t\"context\"\n\t\"io\"\n)\n\ntype Component interface {\n\tRender(ctx context.Context, w io.Writer) error\n}\n",
		"cmd/templ/main.go": strings.ReplaceAll(generator, "VERSION", version),
	}}
}

const generator = `package main

import (
	"io/fs"
	"os"
	"path/filepath"
	"strings"
)

func main() {
	if len(os.Args) < 2 || os.Args[1] != "generate" {
		os.Exit(2)
	}
	root := "."
	for i := 2; i+1 < len(os.Args); i++ {
		if os.Args[i] == "-path" {
			root = os.Args[i+1]
		}
	}
	err := filepath.WalkDir(root, func(p string, d fs.DirEntry, err error) error {
		if err != nil || d.IsDir() || !strings.HasSuffix(p, ".templ") {
			return err
		}
		src, err := os.ReadFile(p)
		if err != nil {
			return err
		}
		pkg := "main"
		for _, line := range strings.Split(string(src), "\n") {
			if name, ok := strings.CutPrefix(line, "package "); ok {
				pkg = strings.TrimSpace(name)
				break
			}
		}
		out := "// Code generated by templ - DO NOT EDIT.\n\n// templ: version: VERSION\npackage " + pkg +
			"\n\nimport \"github.com/a-h/templ\"\n\nvar _ templ.Component\n"
		return os.WriteFile(strings.TrimSuffix(p, ".templ")+"_templ.go", []byte(out), 0o644)
	})
	if err != nil {
		os.Exit(1)
	}
}
`

// Templsite writes a stand-in templsite module to a temp dir, requiring
// the templ stand-in at templVersion, with one package (pkg/site) that
// imports it. It returns the directory, for a replace.
func Templsite(t *testing.T, templVersion string) string {
	t.Helper()
	dir := t.TempDir()
	WriteFiles(t, dir, map[string]string{
		"go.mod":           "module github.com/dmoose/templsite\n\ngo 1.26\n\nrequire " + TemplPath + " " + templVersion + "\n",
		"pkg/site/site.go": "package site\n\nimport \"github.com/a-h/templ\"\n\nvar _ templ.Component\n",
	})
	return dir
}

// WriteFiles writes files under dir.
func WriteFiles(t *testing.T, dir string, files map[string]string) {
	t.Helper()
	for name, body := range files {
		write(t, filepath.Join(dir, name), body)
	}
}

func write(t *testing.T, path, body string) {
	t.Helper()
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte(body), 0o644); err != nil {
		t.Fatal(err)
	}
}

// writeZip writes a module zip: every file under <path>@<version>/.
func writeZip(t *testing.T, path string, m Module) {
	t.Helper()
	f, err := os.Create(path)
	if err != nil {
		t.Fatal(err)
	}
	zw := zip.NewWriter(f)
	names := make([]string, 0, len(m.Files))
	for name := range m.Files {
		names = append(names, name)
	}
	slices.Sort(names)
	for _, name := range names {
		w, err := zw.Create(m.Path + "@" + m.Version + "/" + name)
		if err != nil {
			t.Fatal(err)
		}
		if _, err := w.Write([]byte(m.Files[name])); err != nil {
			t.Fatal(err)
		}
	}
	if err := zw.Close(); err != nil {
		t.Fatal(err)
	}
	if err := f.Close(); err != nil {
		t.Fatal(err)
	}
}
